"""Generate src/strip_table.h: optional diacritics removed by -stripProb.

Two tables, computed with Python's unicodedata:
- kStripMarks: combining marks that are dropped. These are the general
  combining diacritics (tones, accents) plus the optional vowel and
  cantillation marks of Arabic and Hebrew. Marks that are part of a letter in
  other scripts (Indic vowel signs, for example) are not included.
- kStripBase: precomposed letters of the Latin, Greek and Cyrillic scripts
  whose canonical decomposition is one base letter plus such marks, mapped to
  that base letter (e.g. U+1EBF LATIN SMALL LETTER E WITH CIRCUMFLEX AND ACUTE
  -> e).

Usage: python3 tools/gen_strip_table.py > src/strip_table.h
"""
import sys
import unicodedata

MARK_BLOCKS = [
    (0x0300, 0x036F),  # Combining Diacritical Marks
    (0x1AB0, 0x1AFF),  # Combining Diacritical Marks Extended
    (0x1DC0, 0x1DFF),  # Combining Diacritical Marks Supplement
    (0x20D0, 0x20FF),  # Combining Diacritical Marks for Symbols
    (0xFE20, 0xFE2F),  # Combining Half Marks
    (0x0591, 0x05C7),  # Hebrew cantillation and points
    (0x064B, 0x065F),  # Arabic harakat
    (0x0670, 0x0670),  # Arabic superscript alef
    (0x06D6, 0x06ED),  # Arabic Quranic annotation marks
]
BASE_BLOCKS = [
    (0x0000, 0x024F), (0x1E00, 0x1EFF), (0x2C60, 0x2C7F), (0xA720, 0xA7FF),
    (0xAB30, 0xAB6F),  # Latin
    (0x0370, 0x03FF), (0x1F00, 0x1FFF),  # Greek
    (0x0400, 0x052F), (0x1C80, 0x1C8F), (0x2DE0, 0x2DFF), (0xA640, 0xA69F),  # Cyrillic
]


def is_mark(cp):
    return unicodedata.category(chr(cp)).startswith("M") and any(
        a <= cp <= b for a, b in MARK_BLOCKS)


def ranges(cps):
    start = prev = None
    for cp in cps:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            yield start, prev
            start = prev = cp
    if start is not None:
        yield start, prev


def main():
    marks = sorted(cp for a, b in MARK_BLOCKS for cp in range(a, b + 1) if is_mark(cp))
    bases = []
    for a, b in BASE_BLOCKS:
        for cp in range(a, b + 1):
            d = unicodedata.normalize("NFD", chr(cp))
            if len(d) > 1 and all(is_mark(ord(c)) for c in d[1:]):
                bases.append((cp, ord(d[0])))
    bases.sort()  # the C++ lookup is a binary search
    out = sys.stdout
    out.write("// Generated by tools/gen_strip_table.py with Unicode %s; do not edit.\n"
              % unicodedata.unidata_version)
    out.write("#pragma once\n\n#include <cstdint>\n\n#include \"norm_table.h\"\n\n")
    out.write("namespace bytefast {\nnamespace unicode {\n\n")
    out.write("// Combining marks removed by -stripProb, as ranges sorted by start.\n")
    out.write("constexpr CodeRange kStripMarks[] = {\n")
    rs = list(ranges(marks))
    for i in range(0, len(rs), 4):
        out.write("    %s,\n" % ", ".join("{0x%04X, 0x%04X}" % r for r in rs[i:i + 4]))
    out.write("};\n\nconstexpr int kStripMarksSize = %d;\n\n" % len(rs))
    out.write("struct CodeMap {\n  uint32_t from;\n  uint32_t to;\n};\n\n")
    out.write("// Precomposed letters and their base letter, sorted by code point.\n")
    out.write("constexpr CodeMap kStripBase[] = {\n")
    for i in range(0, len(bases), 6):
        out.write("    %s,\n" % ", ".join("{0x%04X, 0x%04X}" % m for m in bases[i:i + 6]))
    out.write("};\n\nconstexpr int kStripBaseSize = %d;\n\n" % len(bases))
    out.write("} // namespace unicode\n} // namespace bytefast\n")


if __name__ == "__main__":
    main()
